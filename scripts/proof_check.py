"""Machine verification of every lemma in the proof of the class formula
sigma_hat[f] = [r_n][f]^{-1}  (see class-formula-proof.md).

For each primitive reduced form f = (a,b,c) of disc D = 1 - n^2 (n odd):

Lemma A: with K = {(s,t): (n+1)s = bt, bs = -(n-1)t mod 2a} (index a in Z^2),
  an oriented basis w_1, w_2 of K (t_1 s_2 - s_1 t_2 = a), u_k = s_k + i t_k,
  v_k = ((n+bi)u_k + conj(u_k)) / (2ia), the matrix P with columns
  (u_1, u_2)^T, (v_1, v_2)^T lies in SL_2(Z[i]) and P^dagger M_0 P = M_f.

Lemma B: the sigma-image Gram M' = -conj((P^{-1})^dagger M_0 P^{-1}) has
  real part given by the form (1/2a) g|_K, g(s,t) = (n+1)s^2 + (n-1)t^2,
  in the basis determined below, and Im-part +-n.

Lemma C: the map (s,t) -> s(n+1)/2 + t*omega identifies K with an
  O-ideal c (omega-stable), and c = s_ideal * a_f, where
  s_ideal = ((n+1)/2, omega), a_f = (a, b/2 + omega).

Conclusion: the image class is compose(r_n, f)^{op} = r_n o f^{-1}.
"""
