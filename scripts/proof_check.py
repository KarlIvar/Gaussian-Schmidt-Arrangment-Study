def K_basis(n, a, b):
    """Oriented basis (t1*s2 - s1*t2 = a) of the congruence lattice K."""
    m = 2 * a
    pts = [(s, t) for s in range(m) for t in range(m)
           if ((n + 1) * s - b * t) % m == 0 and (b * s + (n - 1) * t) % m == 0]
    # lattice generated by pts and (m,0),(0,m): HNF via simple reduction
    gens = pts + [(m, 0), (0, m)]
    # 2D HNF
    from math import gcd as _g
    # find primitive vector along first column structure: use standard algo
    import itertools
    # reduce: bring to basis via repeated gcd steps
    basis = []
    v1 = None
    # first basis vector: gcd of all s-components with combos
    # simple approach: use Smith-like reduction on the generator matrix
    rows = gens[:]
    # HNF of the lattice spanned by rows (as row lattice in Z^2)
    def hnf(rows):
        rows = [list(r) for r in rows if r != (0, 0)]
        # make column 0 have a single nonzero via gcd
        while True:
            nz = [r for r in rows if r[0] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda r: abs(r[0]))
            p = nz[0]
            for r in nz[1:]:
                q = r[0] // p[0]
                r[0] -= q * p[0]
                r[1] -= q * p[1]
            rows = [r for r in rows if r != [0, 0]]
        top = [r for r in rows if r[0] != 0]
        rest = [r for r in rows if r[0] == 0]
        assert len(top) == 1
        while True:
            nzz = [r for r in rest if r[1] != 0]
            if len(nzz) <= 1:
                break
            nzz.sort(key=lambda r: abs(r[1]))
            p = nzz[0]
            for r in nzz[1:]:
                q = r[1] // p[1]
                r[1] -= q * p[1]
            rest = [r for r in rest if r != [0, 0]]
        sec = [r for r in rest if r[1] != 0]
        assert len(sec) == 1
        return top[0], sec[0]
    b1, b2 = hnf(rows)
    w1, w2 = tuple(b1), tuple(b2)
    d = w1[1] * w2[0] - w1[0] * w2[1]          # t1*s2 - s1*t2
    assert abs(d) == a, (n, a, b, d)
    if d == -a:
        w2 = (-w2[0], -w2[1])
    return w1, w2


