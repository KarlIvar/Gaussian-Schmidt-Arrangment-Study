def build_P(n, f):
    a, b, c = f
    (s1, t1), (s2, t2) = K_basis(n, a, b)
    u1, u2 = (s1, t1), (s2, t2)                 # u_k = s_k + i t_k

    def v_of(u):
        # ((n + b i)(s + t i) + (s - t i)) / (2 i a)
        s, t = u
        num = ((n + 1) * s - b * t, b * s + (n - 1) * t)
        # divide by 2ia = (0, 2a): 1/(2ia) = -i/(2a)
        # num * (-i) = (num_im, -num_re)
        z = (num[1], -num[0])
        assert z[0] % (2 * a) == 0 and z[1] % (2 * a) == 0, (n, f, u)
        return (z[0] // (2 * a), z[1] // (2 * a))
    v1, v2 = v_of(u1), v_of(u2)
    P = ((u1, v1), (u2, v2))                    # columns (u1,u2), (v1,v2)
    assert det(P) == (1, 0), (n, f)
    Mf = herm_from_triple(2 * a, (b, -n), 2 * c)
    assert matmul(dagger(P), matmul(M0, P)) == Mf, (n, f)
    return P, ((s1, t1), (s2, t2))


def omega_action(n, w):
    """omega * (s,t) in the coordinates (s,t) <-> s(n+1)/2 + t omega."""
    s, t = w
    return ((1 - n) * t // 2, (n + 1) * s // 2)


def lattice_eq(gens1, gens2, box=None):
    """Equality of 2D lattices given generators (integer pairs)."""
    def hnf2(gens):
        rows = [list(g) for g in gens if g != (0, 0)]
        while True:
            nz = [r for r in rows if r[0] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda r: abs(r[0]))
            p = nz[0]
            for r in nz[1:]:
                q = r[0] // p[0]
                r[0] -= q * p[0]; r[1] -= q * p[1]
            rows = [r for r in rows if r != [0, 0]]
        top = [r for r in rows if r[0] != 0]
        rest = [r for r in rows if r[0] == 0 and r[1] != 0]
        while len(rest) > 1:
            rest.sort(key=lambda r: abs(r[1]))
            p = rest[0]
            for r in rest[1:]:
                q = r[1] // p[1]
                r[1] -= q * p[1]
            rest = [r for r in rest if r[1] != 0]
        t0 = top[0]
        s0 = rest[0] if rest else [0, 0]
        if s0 != [0, 0]:
            t0 = [t0[0], t0[1] % abs(s0[1])] if s0[1] else t0
        if t0[0] < 0:
            t0 = [-t0[0], -t0[1]]
        if s0[1] < 0:
            s0 = [0, -s0[1]]
        if s0[1]:
            t0[1] %= s0[1]
        return (tuple(t0), tuple(s0))
    return hnf2(gens1) == hnf2(gens2)


def run(nmax=25):
    total = 0
    for n in range(3, nmax + 1, 2):
        D = 1 - n * n
        rn = reduce_form((n - 1) // 2, 0, (n + 1) // 2)
        for f in classes_of_disc(D):
            if not is_primitive(f):
                continue
            a, b, c = f
            P, (w1, w2) = build_P(n, f)              # Lemma A
            X = inv_sl2(P)
            eps2, yM2, f2 = oriented_data(M_of_X(sigma(X)))
            assert yM2 == n and eps2 == -1

            # Lemma B: predicted image form from g|_K
            def g(w, w_=None):
                s, t = w
                s_, t_ = w_ if w_ else w
                return (n + 1) * s * s_ + (n - 1) * t * t_
            a2, c2 = g(w2), g(w1)
            b2 = g(w1, w2)
            assert a2 % (2 * a) == 0 and c2 % (2 * a) == 0 and (2 * b2) % (2 * a) == 0
            fB = reduce_form(a2 // (2 * a), -b2 // a, c2 // (2 * a))
            assert fB == f2, (n, f, fB, f2)

            # Lemma C: K is omega-stable, and c = s_ideal * a_f
            for w in (w1, w2):
                ww = omega_action(n, w)
                # membership in K: solve integer combo of basis
                dd = w1[1] * w2[0] - w1[0] * w2[1]
                x = (ww[1] * w2[0] - ww[0] * w2[1])
                y = (w1[1] * ww[0] - w1[0] * ww[1])
                assert x % dd == 0 and y % dd == 0, (n, f, w)
            # generators of s_ideal * a_f in (s,t)-coordinates:
            prod_gens = [
                (a, 0),                              # (n+1)/2 * a
                (b // 2, (n + 1) // 2),              # (n+1)/2 * (b/2 + omega)
                (0, a),                              # a * omega
                ((1 - n) // 2, b // 2),              # (b/2 + omega) * omega
            ]
            assert lattice_eq(prod_gens, [w1, w2]), (n, f)

            # Conclusion: image class = (r_n o f)^{op} = r_n o f^{-1}
            assert f2 == opp(compose(rn, f, D)) == compose(rn, inverse(f), D)
            total += 1
    print(f"all lemmas verified on {total} primitive classes (odd n <= {nmax})")


if __name__ == "__main__":
    run(int(sys.argv[1]) if len(sys.argv) > 1 else 25)
